local h = require('tests.helper')
local m = require('notes.markdown')

h.t('bullet continuation keeps marker and indent', function()
  h.eq(m.continuation('- foo'), '- ')
  h.eq(m.continuation('  * foo'), '  * ')
  h.eq(m.continuation('\t+ foo'), '\t+ ')
end)

h.t('numbered continuation increments', function()
  h.eq(m.continuation('1. foo'), '2. ')
  h.eq(m.continuation('10) foo'), '11) ')
  h.eq(m.continuation('007. foo'), '008. ')
end)

h.t('checkbox continuation carries checkbox and increments', function()
  h.eq(m.continuation('- [ ] foo'), '- [ ] ')
  h.eq(m.continuation('- [x] foo'), '- [x] ')
  h.eq(m.continuation('1. [ ] foo'), '2. [ ] ')
end)

h.t('empty item ends the list', function()
  h.eq(m.continuation('- '), '')
  h.eq(m.continuation('- [ ]'), '')
  h.eq(m.continuation('1. '), '')
end)

h.t('non-list lines pass through', function()
  h.eq(m.continuation('plain text'), nil)
  h.eq(m.continuation(''), nil)
  h.eq(m.continuation('# heading'), nil)
end)

h.t('toggle_checkbox flips first checkbox on the line', function()
  h.eq(m.toggle_checkbox('- [ ] do it'), '- [x] do it')
  h.eq(m.toggle_checkbox('- [x] do it'), '- [ ] do it')
  h.eq(m.toggle_checkbox('- [X] do it'), '- [ ] do it')
  h.eq(m.toggle_checkbox('plain'), nil)
end)