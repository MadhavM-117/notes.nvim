local h = require('tests.helper')
local l = require('notes.links')
local v = require('notes.vault')

h.t('norm collapses . and ..', function()
  h.eq(v.norm('/a/b/../c'), '/a/c')
  h.eq(v.norm('/a/./b/'), '/a/b')
  h.eq(v.norm('/a//b'), '/a/b')
end)

h.t('relpath goes up and down', function()
  h.eq(v.relpath('/a/b', '/a/b/c.md'), 'c.md')
  h.eq(v.relpath('/a/b/c', '/a/b/d.md'), '../d.md')
  h.eq(v.relpath('/a/b', '/a/b/c/d/e.md'), 'c/d/e.md')
  h.eq(v.relpath('/v/sub', '/v/notes/one.md'), '../notes/one.md')
end)

h.t('parse_line finds links with offsets', function()
  local r = l.parse_line('see [foo](bar.md) now')
  h.eq(#r, 1)
  h.eq(r[1].label, 'foo')
  h.eq(r[1].target, 'bar.md')
  h.eq(r[1].lstart, 5)
  h.eq(r[1].lend, 17)
end)

h.t('parse_line finds multiple links', function()
  local r = l.parse_line('[a](a.md) and [b](b.md)')
  h.eq(#r, 2)
  h.eq(r[2].target, 'b.md')
end)

h.t('resolve_target pads .md and resolves relative', function()
  h.eq(l.resolve_target('bar', '/a/b/note.md'), '/a/b/bar.md')
  h.eq(l.resolve_target('bar.md', '/a/b/note.md'), '/a/b/bar.md')
  h.eq(l.resolve_target('../x.md', '/a/b/note.md'), '/a/x.md')
  h.eq(l.resolve_target('/abs/y.md', '/a/b/note.md'), '/abs/y.md')
end)

h.t('resolve_target ignores externals and fragments', function()
  h.eq(l.resolve_target('https://x.com/y', '/a/b/note.md'), nil)
  h.eq(l.resolve_target('mailto:a@b.c', '/a/b/note.md'), nil)
  h.eq(l.resolve_target('#frag', '/a/b/note.md'), nil)
end)

h.t('split_target handles titles and fragments', function()
  local s = l.split_target('x.md "title"')
  h.eq(s.path, 'x.md')
  h.eq(s.title, ' "title"')
  local s2 = l.split_target('<x.md>')
  h.eq(s2.path, 'x.md')
  local s3 = l.split_target('x.md#part')
  h.eq(s3.path, 'x.md')
  h.eq(s3.frag, 'part')
end)

h.t('rewrite_content rewrites only moved links', function()
  local content = 'a [one](sub/one.md)\nb [two](../other/two.md#s)\nc [ext](https://x.com)'
  local out = l.rewrite_content(content, '/v/sub/one.md', '/v/notes/one.md', '/v')
  h.eq(out, 'a [one](notes/one.md)\nb [two](../other/two.md#s)\nc [ext](https://x.com)')
end)

h.t('rewrite_content recomputes path from deep reader', function()
  h.eq(l.rewrite_content('[one](one.md)', '/v/sub/one.md', '/v/notes/one.md', '/v/sub'),
    '[one](../notes/one.md)')
end)

h.t('rewrite_content handles extensionless targets', function()
  h.eq(l.rewrite_content('[one](one)', '/v/one.md', '/v/new/one.md', '/v'), '[one](new/one.md)')
end)

h.t('rewrite_content preserves titles', function()
  local out = l.rewrite_content('[one](one.md "keep")', '/v/one.md', '/v/new/one.md', '/v')
  h.eq(out, '[one](new/one.md "keep")')
end)

h.t('rewrite_content returns nil when nothing changed', function()
  h.eq(l.rewrite_content('[x](other.md)', '/v/one.md', '/v/new/one.md', '/v'), nil)
end)