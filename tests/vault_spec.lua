local h = require('tests.helper')
local v = require('notes.vault')
local notes = require('notes')

h.t('containing finds the vault holding a path', function()
  local tmp = vim.fn.tempname()
  vim.fn.mkdir(tmp .. '/vault/sub', 'p')
  notes.setup({ default_vault = tmp .. '/vault', vaults = { other = tmp .. '/other' } })
  h.eq(v.containing(tmp .. '/vault/sub/note.md').name, 'default')
  h.eq(v.containing(tmp .. '/other/note.md').name, 'other')
  h.eq(v.containing('/elsewhere/note.md'), nil)
  h.eq(v.containing(''), nil)
  notes.setup({}) -- restore defaults for any later cases
  vim.fn.delete(tmp, 'rf')
end)

h.t('get_todos lists checkbox items across the vault', function()
  local tmp = vim.fn.tempname()
  vim.fn.mkdir(tmp .. '/v/sub', 'p')
  vim.fn.writefile({ '- [ ] a', 'text', '- [x] b' }, tmp .. '/v/one.md')
  vim.fn.writefile({ '- [X] c' }, tmp .. '/v/sub/two.md')
  notes.setup({ default_vault = tmp .. '/v' })
  local items = notes.get_todos()
  h.eq(#items, 3, 'todo count')
  h.eq(items[1].lnum, 1, 'first lnum')
  h.eq(items[1].path:match('([^/]+)%.md$'), 'one', 'first path')
  h.eq(notes.get_todos('default')[1].line, '- [ ] a', 'by name lookup')
  notes.setup({})
  vim.fn.delete(tmp, 'rf')
end)
